// Hebrew service pages. Voice matches the site: first person, feminine, "אתם".
// Facts already on the homepage (process, code, ownership, warranty, AI) are
// reused. Strings in `ownerReviewClaims` are new first-person lines for Mor
// to approve or edit. They are also listed in the pull request.

export type TextPart = string | { text: string; href: string };
export type Paragraph = TextPart[];

export type FaqItem = {
  question: string;
  answer: string[];
};

export type ProseSection = {
  type: "prose";
  id: string;
  heading: string;
  paragraphs: Paragraph[];
  items?: string[];
  ordered?: boolean;
};

export type SplitSection = {
  type: "split";
  id: string;
  heading: string;
  columns: {
    heading: string;
    paragraphs?: Paragraph[];
    items: string[];
  }[];
};

export type StepsSection = {
  type: "steps";
  id: string;
  heading: string;
  paragraphs?: Paragraph[];
  steps: { title: string; detail: string }[];
};

export type ServiceSection = ProseSection | SplitSection | StepsSection;

export type ServiceDocument = {
  /** `null` on the hub. */
  slug: string | null;
  /** Locale-less path, e.g. `/services/mvp`. */
  path: string;
  /** Hebrew document title. The layout adds `| Moriz Studio` only when this
   * file is not used with an absolute title. Pages set the full title. */
  title: string;
  description: string;
  keyword: string;
  heading: string;
  answer: Paragraph[];
  sections: ServiceSection[];
  faq: FaqItem[];
  articleSlugs: string[];
  projectSlugs: string[];
  relatedSlugs: string[];
  cta: string;
  showCatalog: boolean;
};

