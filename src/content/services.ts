function p(text: string): Paragraph {
  return [text];
}

export function paragraphText(paragraph: Paragraph) {
  return paragraph
    .map((part) => (typeof part === "string" ? part : part.text))
    .join("");
}

export function paragraphsText(paragraphs: Paragraph[]) {
  return paragraphs.map(paragraphText).join("\n\n");
}

